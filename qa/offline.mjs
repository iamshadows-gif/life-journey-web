import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, offline: true });
const page = await context.newPage();
const errors = [];
const external = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (/^https?:/.test(r.url())) external.push(r.url()); });
await page.goto('file:///home/user/deliverables/interwoven.html', { waitUntil: 'load' });
await page.evaluate(() => document.fonts.ready);
assert.ok(await page.locator('canvas').evaluate(c => c.width > 0));
assert.ok(await page.evaluate(() => document.fonts.check('20px Cormorant')));
await page.locator('[data-age="85"]').click();
await page.waitForFunction(() => document.querySelector('#age-progress').value > 84.99);
await page.waitForTimeout(350);
await page.screenshot({ path: '/home/user/qa/offline-ending.png' });
await page.locator('#restart').click();
await page.waitForFunction(() => document.querySelector('#age-progress').value < 1);
await page.locator('#sound-toggle').click();
await page.waitForFunction(() => !document.querySelector('audio').paused && document.querySelector('#sound-toggle').getAttribute('aria-pressed') === 'true');
assert.equal(await page.locator('#sound-toggle').getAttribute('aria-pressed'), 'true');
await page.locator('#sound-toggle').click();
console.log('Offline file: fonts, scroll, ending, restart, audio PASS');
// Match the file viewer: opaque-origin sandbox, scripts enabled, network off.
const parent = await context.newPage();
parent.on('pageerror', e => errors.push(e.message));
await parent.setContent('<html><body style="margin:0"><iframe style="width:100vw;height:100vh;border:0" id="preview" sandbox="allow-scripts"></iframe></body></html>');
const html = await readFile('/home/user/deliverables/interwoven.html', 'utf8');
await parent.locator('iframe').evaluate((el, html) => { el.srcdoc = html; }, html);
const frame = await parent.locator('iframe').elementHandle().then(el => el.contentFrame());
await frame.waitForFunction(() => document.querySelector('canvas')?.width > 0);
await frame.evaluate(() => document.fonts.ready);
await frame.locator('[data-age="36"]').click();
await frame.waitForFunction(() => document.querySelector('#age-progress').value > 35);
assert.ok(await frame.locator('canvas').evaluate(c => c.getContext('2d').getImageData(0,0,1,1).data[3] === 255));
console.log('Opaque-origin sandbox: canvas, local typography, chapter navigation PASS');
assert.deepEqual(errors, []);
assert.deepEqual(external, []);
console.log(JSON.stringify({ errors, externalRequests: external }, null, 2));
await browser.close();
